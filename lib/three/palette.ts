/**
 * Every colour used by 3D materials lives here (CLAUDE.md: colours only from tokens; 3D materials use these
 * documented palette hexes). HUD and DOM use the CSS tokens in app/globals.css instead.
 *
 * Sources: latecheckout.studio (cream road, ground green, leaf, sky), era palettes from content/eras.ts.
 * Plain strings and numbers only (no three.js import), so the server page and the HUD can import it cheaply.
 *
 * Island agents: put island-specific colours in your own lib/three/palettes/<island>.ts and spread them in
 * your island file. Do not edit this file; ask the foundation owner if a shared colour is missing.
 */

export type EraPalette = {
  /** Lawn / island top. */
  ground: string;
  /** Island cliff sides. */
  cliff: string;
  /** Ring road surface. */
  road: string;
  /** Soft curb along both edges of the road. */
  curb: string;
  /** Era base colour (big surfaces, building walls). */
  base: string;
  /** Era accent (beacons, trims, glow). */
  accent: string;
  /** Pastel building colours, picked by building order. */
  buildings: string[];
  /** Roof colours, picked by building order. */
  roofs: string[];
  /** Tree canopy colours (instanced, picked per tree). */
  leaves: string[];
  trunk: string;
  /** Sky dome gradient, top to horizon. */
  skyTop: string;
  skyBottom: string;
  /** Fog and far sea colour. */
  fog: string;
  sea: string;
  /** Sun (directional) and fill (hemisphere) light. */
  sun: string;
  sunIntensity: number;
  hemiSky: string;
  hemiGround: string;
  hemiIntensity: number;
};

